import pandas as pd
import numpy as np
from sklearn.datasets import load_wine
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LinearRegression, LogisticRegression
from sklearn.neighbors import KNeighborsClassifier
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.cluster import KMeans
from sklearn.metrics import r2_score, mean_squared_error, accuracy_score

# Load the built-in Wine dataset (178 samples, 13 features, 3 classes)
wine = load_wine()
df = pd.DataFrame(wine.data, columns=wine.feature_names)
y_target = wine.target

print(f"Dataset shape: {df.shape}")

# Separate target ('alcohol') and the remaining 12 features
X_reg = df.drop(columns=['alcohol'])
y_reg = df['alcohol']

X_train_r, X_test_r, y_train_r, y_test_r = train_test_split(
    X_reg, y_reg, test_size=0.2, random_state=42
)

# Scale features so coefficients reflect true relative importance
scaler_reg = StandardScaler()
X_train_r_scaled = scaler_reg.fit_transform(X_train_r)
X_test_r_scaled = scaler_reg.transform(X_test_r)

# Train Linear Regression
lr = LinearRegression()
lr.fit(X_train_r_scaled, y_train_r)
y_pred_r = lr.predict(X_test_r_scaled)

print("--- Task 1: Linear Regression ---")
print(f"R² Score: {r2_score(y_test_r, y_pred_r):.4f}")
print(f"MSE:      {mean_squared_error(y_test_r, y_pred_r):.4f}\n")

# Identify the top 2 most influential features by absolute standardized coefficient
coef_df = pd.DataFrame({
    'Feature': X_reg.columns,
    'Coefficient': lr.coef_,
    'Abs_Coefficient': np.abs(lr.coef_)
}).sort_values(by='Abs_Coefficient', ascending=False)

print("Top 2 Most Influential Features on Alcohol Content:")
print(coef_df[['Feature', 'Coefficient']].head(2).to_string(index=False))

X_train_c, X_test_c, y_train_c, y_test_c = train_test_split(
    df, y_target, test_size=0.2, random_state=42, stratify=y_target
)

# Scale features for distance- and gradient-based models
scaler_clf = StandardScaler()
X_train_c_scaled = scaler_clf.fit_transform(X_train_c)
X_test_c_scaled = scaler_clf.transform(X_test_c)

results = []

# 1. Logistic Regression (Before & After Scaling)
log_raw = LogisticRegression(max_iter=5000, random_state=42)
log_raw.fit(X_train_c, y_train_c)
acc_log_raw = accuracy_score(y_test_c, log_raw.predict(X_test_c))
results.append(("Logistic Regression", "Unscaled", acc_log_raw))

log_scaled = LogisticRegression(max_iter=5000, random_state=42)
log_scaled.fit(X_train_c_scaled, y_train_c)
acc_log_scaled = accuracy_score(y_test_c, log_scaled.predict(X_test_c_scaled))
results.append(("Logistic Regression", "Scaled", acc_log_scaled))

# 2. KNN (Before & After Scaling)
knn_raw = KNeighborsClassifier(n_neighbors=5)
knn_raw.fit(X_train_c, y_train_c)
acc_knn_raw = accuracy_score(y_test_c, knn_raw.predict(X_test_c))
results.append(("KNN (k=5)", "Unscaled", acc_knn_raw))

knn_scaled = KNeighborsClassifier(n_neighbors=5)
knn_scaled.fit(X_train_c_scaled, y_train_c)
acc_knn_scaled = accuracy_score(y_test_c, knn_scaled.predict(X_test_c_scaled))
results.append(("KNN (k=5)", "Scaled", acc_knn_scaled))

# 3. Decision Tree (Tree models are scale-invariant)
dt = DecisionTreeClassifier(random_state=42)
dt.fit(X_train_c, y_train_c)
acc_dt = accuracy_score(y_test_c, dt.predict(X_test_c))
results.append(("Decision Tree", "Unscaled", acc_dt))

# 4. Random Forest (Tree models are scale-invariant)
rf = RandomForestClassifier(n_estimators=100, random_state=42)
rf.fit(X_train_c, y_train_c)
acc_rf = accuracy_score(y_test_c, rf.predict(X_test_c))
results.append(("Random Forest", "Unscaled", acc_rf))

# Summary Table
summary_df = pd.DataFrame(results, columns=["Model", "Preprocessing", "Test Accuracy"])
summary_df["Test Accuracy (%)"] = (summary_df["Test Accuracy"] * 100).round(2)

print("\n--- Task 2: Classification Showdown ---")
print(summary_df[["Model", "Preprocessing", "Test Accuracy (%)"]].to_string(index=False))

print(f"\nKNN Accuracy Jump:                 +{(acc_knn_scaled - acc_knn_raw) * 100:.2f}%")
print(f"Logistic Regression Accuracy Jump: +{(acc_log_scaled - acc_log_raw) * 100:.2f}%")

# Scale all 13 features (no target column used)
scaler_unsup = StandardScaler()
X_scaled_all = scaler_unsup.fit_transform(df)

# Fit K-Means with 3 clusters
kmeans = KMeans(n_clusters=3, random_state=42, n_init=10)
clusters = kmeans.fit_predict(X_scaled_all)

# Compare discovered clusters against actual wine classes
ct = pd.crosstab(
    pd.Series(y_target, name='Actual Wine Class'),
    pd.Series(clusters, name='K-Means Cluster')
)

print("\n--- Task 3: Unsupervised Discovery (Crosstab) ---")
print(ct)

